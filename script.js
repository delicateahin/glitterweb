// Función para actualizar ficha
function setCharacter(key){
  const c = data[key] || data['about'];

  // actualizar logo
  document.getElementById('brand-logo').src = c.logo;

  // mostrar/ocultar secciones según el tipo
  const profileSection = document.querySelector('.profile');
  const storySection = document.querySelector('.story');
  const quoteSection = document.querySelector('.quote-section');
  const aboutSection = document.querySelector('.about-section');
  const destinySection = document.querySelector('.destiny-section');
  const nowPlaying = document.querySelector('.now-playing');

  // ocultar todo primero
  profileSection.style.display = 'none';
  storySection.style.display = 'none';
  quoteSection.style.display = 'none';
  aboutSection.style.display = 'none';
  destinySection.style.display = 'none';
  nowPlaying.style.display = 'none';

  if (c.type === 'about') {
    // mostrar about us
    aboutSection.style.display = 'block';
  } else if (c.type === 'destiny') {
    // mostrar destiny
    destinySection.style.display = 'block';
    
    // cargar imágenes de destiny
    const destinyGallery = document.getElementById('destiny-gallery');
    destinyGallery.innerHTML = '';
    c.images.forEach(img => {
      const imgEl = document.createElement('img');
      imgEl.src = img;
      imgEl.alt = 'Destiny';
      destinyGallery.appendChild(imgEl);
    });
    
    document.getElementById('destiny-story').textContent = c.story;
  } else {
    // mostrar ficha normal
    nowPlaying.style.display = 'block';
    profileSection.style.display = 'flex';
    storySection.style.display = 'block';
    quoteSection.style.display = 'block';

    // now playing
    const firstSong = c.songs[0];
    const trackId = firstSong.match(/track\/([a-zA-Z0-9]+)/)?.[1];
    if (trackId) {
      // obtener info de la canción desde el link (simplificado)
      const songInfo = c.songs[0].includes('0Q5VnK2DYzRyfqQRJuUtvi') ? 'Lucky=One — cosmosy' :
                       c.songs[0].includes('2Y7IdLEr2vSFN3Fc1BBjwQ') ? 'GOTCHA (Baddest Eros) — IVE' :
                       c.songs[0].includes('2qwyjoSsSr3M7HTt611Q5O') ? 'Wind flower — MAMAMOO' :
                       c.songs[0].includes('41P6Tnd8KIHqON0QIydx6a') ? 'the perfect pair — beabadoobee' :
                       c.songs[0].includes('4R1fcNFZqbzlQdme9N4xyy') ? 'Flatline — 5 Seconds of Summer' : 
                       'Song title';
      document.getElementById('now-playing-text').textContent = `▶ now playing ... ${songInfo}`;
    }

    // actualizar galería de imágenes
    const gallery = document.getElementById('char-gallery');
    gallery.innerHTML = '';
    c.images.forEach(img => {
      const imgEl = document.createElement('img');
      imgEl.src = img;
      imgEl.alt = `Foto de ${c.name}`;
      gallery.appendChild(imgEl);
    });

    // actualizar DOM básico
    document.getElementById('char-name').textContent = c.name;
    document.getElementById('char-origin').textContent = c.origin;
    document.getElementById('char-parents').textContent = c.parents;
    document.getElementById('char-birth').textContent = c.birth;
    document.getElementById('char-age').textContent = c.age;
    document.getElementById('char-sign').textContent = c.sign;
    document.getElementById('char-mbti').textContent = c.mbti;
    document.getElementById('char-emoji').textContent = c.emoji;
    document.getElementById('char-animal').textContent = c.animal;
    document.getElementById('char-cant-live').textContent = c.cantLiveWithout;
    document.getElementById('char-food').textContent = c.food;
    document.getElementById('char-place').textContent = c.place;
    document.getElementById('char-hobbie').textContent = c.hobbie;
    document.getElementById('char-dream').textContent = c.dream;
    
    // historia con poderes al final
    const storyDiv = document.getElementById('char-story');
    storyDiv.innerHTML = `<p>${c.story}</p>`;
    
    // poderes como hashtags
    const powersDiv = document.getElementById('char-powers');
    const powerNames = c.power.split('&').map(p => {
      const name = p.split('(')[0].trim();
      return '#' + name.toUpperCase().replace(/\s+/g, '_').replace(/[áÁ]/g, 'A').replace(/[éÉ]/g, 'E').replace(/[íÍ]/g, 'I').replace(/[óÓ]/g, 'O').replace(/[úÚ]/g, 'U').replace(/[ñÑ]/g, 'N');
    }).join(' ');
    powersDiv.textContent = powerNames;
    
    document.getElementById('char-quote').textContent = c.quote;
    
    // cualidades (eliminadas)
    // document.getElementById('char-quality-pos').textContent = c.qualities.positive;
    // document.getElementById('char-quality-neg').textContent = c.qualities.negative;

    // canciones (eliminadas - ahora solo now playing arriba)
    // const songsContainer = document.getElementById('char-songs');
    // songsContainer.innerHTML = '';
  }

  // actualizar botón activo del menú
  document.querySelectorAll('.menu-btn').forEach(btn=>{
    btn.classList.remove('active');
  });
  const activeBtn = document.querySelector(`.menu-btn[data-character="${key}"]`);
  if(activeBtn) activeBtn.classList.add('active');

  // cambiar data-character en body para CSS dinámico
  document.body.setAttribute('data-character', key);
}

// listeners menú
document.querySelectorAll('.menu-btn').forEach(btn=>{
  btn.addEventListener('click', ()=>{
    const char = btn.dataset.character;
    setCharacter(char);
  });
});

// listener para el logo
document.getElementById('brand-logo').addEventListener('click', ()=>{
  setCharacter('about');
});

// Inicializar con about
setCharacter('about');
